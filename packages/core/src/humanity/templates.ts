/**
 * 随机获取模板
 */
export function getRandomTemplate(templates: string[]): string {
  return templates[Math.floor(Math.random() * templates.length)];
}

/**
 * 获取随机呼吸段
 */
export function getRandomBreathingText(type: BreathingType): string {
  const templates = BREATHING_TEMPLATES[type];
  return getRandomTemplate(templates);
}

/**
 * 获取随机沉默层替换
 */
export function getRandomSilenceReplacement(
  original: string
): { replaced: boolean; text: string } {
  for (const rule of SILENCE_REPLACEMENTS) {
    if (rule.pattern.test(original)) {
      const replacement = getRandomTemplate(rule.replacements);
      return {
        replaced: true,
        text: original.replace(rule.pattern, replacement),
      };
    }
  }
  return { replaced: false, text: original };
}

/**
 * 生成矛盾性行为文本
 */
export function generateSelfContradiction(
  type: keyof typeof SELF_CONTRADICTION_TEMPLATES,
  ...args: string[]
): string {
  const templates = SELF_CONTRADICTION_TEMPLATES[type];
  const template = getRandomTemplate(templates);
  return args.length > 0 ? template.format(...args) : template;
}

/**
 * 辅助函数：格式化字符串模板
 */
declare global {
  interface String {
    format(...args: string[]): string;
  }
}

if (typeof String.prototype.format === "undefined") {
  String.prototype.format = function (...args: string[]): string {
    return this.replace(/\{(\d+)\}/g, (_, index) => args[index] || "");
  };
}
